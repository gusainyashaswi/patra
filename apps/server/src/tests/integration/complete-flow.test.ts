import { describe, it, expect, beforeAll, afterAll, beforeEach } from "vitest";
import { randomUUID } from "node:crypto";
import request from "supertest";
import { app } from "../../app.js";
import { setupTestDb, teardownTestDb, clearTestDb, seedTestContext } from "../testHelper.js";
import { Campaign } from "../../models/campaign.model.js";
import { Contact } from "../../models/audience.model.js";
import { createSendWorker } from "../../worker.js";
import { fakeTransport } from "../../transports/index.js";

describe("Complete owner API workflow", () => {
  beforeAll(setupTestDb);
  afterAll(teardownTestDb);
  beforeEach(clearTestDb);
  it("imports, publishes, queues an immutable version, reports results, and logs out", async () => {
    const ctx = await seedTestContext();
    const login = await request(app).post("/api/auth/login").send({ email: ctx.user.email, password: "Password123!" });
    expect(login.status).toBe(200);
    const token = login.body.data.accessToken;
    const base = `/api/orgs/${ctx.organization.id}`;
    const csv = Buffer.from("email,name\nflow@example.test,Flow Owner\n");
    const preview = await request(app).post(base + "/contacts/import/preview?filename=flow.csv").auth(token, { type: "bearer" }).set("Content-Type", "application/octet-stream").send(csv);
    expect(preview.status).toBe(200);
    expect(await Contact.countDocuments({ organizationId: ctx.organization.id })).toBe(3);
    const imported = await request(app).post(base + `/contacts/import?filename=flow.csv&listName=Flow&requestId=${randomUUID()}`).auth(token, { type: "bearer" }).set("Content-Type", "application/octet-stream").send(csv);
    expect(imported.status).toBe(201);
    const draft = { name: "Flow template", subject: "Hello {{name}}", previewText: "Preview", page: { bg: "#ffffff", text: "#292524", width: 600, align: "left" }, blocks: [{ id: "welcome", type: "text", text: "Hello {{name}}", size: 18, weight: 400 }] };
    const template = await request(app).post(base + "/templates").auth(token, { type: "bearer" }).send(draft);
    expect(template.status).toBe(201);
    const templatePath = base + `/templates/${template.body.data.id}`;
    const published = await request(app).post(templatePath + "/publish").auth(token, { type: "bearer" }).send({ revision: template.body.data.revision });
    expect(published.status).toBe(201);
    const campaign = await request(app).post(base + "/campaigns").auth(token, { type: "bearer" }).send({ name: "Flow campaign", templateVersionId: published.body.data.id, senderIdentityId: ctx.sender.id, listId: imported.body.data.list.id });
    expect(campaign.status).toBe(201);
    const campaignPath = base + `/campaigns/${campaign.body.data.id}`;
    expect((await request(app).post(campaignPath + "/send").auth(token, { type: "bearer" })).status).toBe(202);
    expect((await request(app).put(templatePath + "/draft").auth(token, { type: "bearer" }).send({ revision: template.body.data.revision, draft: { ...draft, subject: "Changed later" } })).status).toBe(200);
    createSendWorker(ctx.transport.id, 10);
    const deadline = Date.now() + 8000;
    while (Date.now() < deadline && (await Campaign.findById(campaign.body.data.id))?.status !== "COMPLETED") await new Promise(resolve => setTimeout(resolve, 100));
    expect((await Campaign.findById(campaign.body.data.id))?.status).toBe("COMPLETED");
    expect(fakeTransport.allSends[0].subject).toBe("Hello Flow Owner");
    const results = await request(app).get(campaignPath + "/recipients/export?status=SENT").auth(token, { type: "bearer" });
    expect(results.text).toContain("flow@example.test");
    const overview = await request(app).get(base + "/overview").auth(token, { type: "bearer" });
    expect(overview.body.data.stats.sent).toBe(1);
    expect((await request(app).post("/api/auth/logout").auth(token, { type: "bearer" })).status).toBe(200);
    expect((await request(app).post("/api/auth/refresh").send({ refreshToken: login.body.data.refreshToken })).status).toBe(401);
  });
});
